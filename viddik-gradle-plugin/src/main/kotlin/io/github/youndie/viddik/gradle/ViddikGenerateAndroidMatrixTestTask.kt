package io.github.youndie.viddik.gradle

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction
import org.gradle.work.DisableCachingByDefault

/**
 * Writes the JUnit 4 class the Android matrix runs on each emulator: one test for the whole
 * `commonMain` registry, since a test per fixture cost an activity per fixture (see `ViddikAndroidCapture`).
 *
 * The same reasoning as [ViddikGenerateTestsTask]: KSP would skip `androidDeviceTest` for having no
 * sources, and a task with an output directory always runs.
 */
@DisableCachingByDefault(
    because = "The output is a fixed string; writing it is cheaper than looking it up in a build cache.",
)
public abstract class ViddikGenerateAndroidMatrixTestTask : DefaultTask() {
    @get:OutputDirectory
    public abstract val outputDir: DirectoryProperty

    @TaskAction
    public fun generate() {
        val root = outputDir.get().asFile
        root.deleteRecursively()
        val target = root.resolve(PACKAGE.replace('.', '/'))
        target.mkdirs()
        target.resolve("$CLASS_NAME.kt").writeText(SOURCE)
    }

    internal companion object {
        const val PACKAGE = "io.github.youndie.viddik.generated"
        const val CLASS_NAME = "GeneratedViddikAndroidMatrix"

        val SOURCE: String =
            """
            // Generated by the io.github.youndie.viddik.android-matrix Gradle plugin. Do not edit.
            package $PACKAGE

            import io.github.youndie.viddik.android.ViddikAndroidCapture
            import org.junit.Test

            public class $CLASS_NAME {
                @Test
                public fun captureAll() {
                    ViddikAndroidCapture.captureAll(GeneratedViddikRegistry.components)
                }
            }

            """.trimIndent()
    }
}
